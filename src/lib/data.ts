export async function getHomePageData() {
  try {
    const baseUrl = process.env.NEXT_PUBLIC_WORDPRESS_URL || "http://shizora.local/";
    
    // Attempt 1: Standard WP REST API with ACF fields for the 'home' page
    const res = await fetch(`${baseUrl}wp-json/wp/v2/pages?slug=home&_fields=acf`, {
      next: { revalidate: 10 } // Revalidate every 10 seconds to keep data fresh
    });
    
    if (res.ok) {
      const data = await res.json();
      if (data && data.length > 0 && data[0].acf) {
        return { acf: data[0].acf };
      }
    }

    // Attempt 2: ACF to REST API options endpoint
    const optionsRes = await fetch(`${baseUrl}wp-json/acf/v3/options/options`, {
      next: { revalidate: 10 }
    });
    
    if (optionsRes.ok) {
      const optionsData = await optionsRes.json();
      if (optionsData && optionsData.acf) {
        return { acf: optionsData.acf };
      }
    }
  } catch (error) {
    console.error("Failed to fetch dynamic data from WordPress, using mock data:", error);
  }
  
  // Fallback to mock data if WordPress endpoints fail
  return mockPageData;
}

